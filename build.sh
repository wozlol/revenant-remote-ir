#!/bin/bash
# ./build.sh        compile and refresh the update file in web/firmware
# ./build.sh flash  same, then flash over the cable (stick in download mode)
cd "$(dirname "$0")" || exit 1
FQBN=m5stack:esp32:m5stack_sticks3
# the web page goes inside the firmware so Revenant can serve it at http://revenant.local
{
  echo "// generated by build.sh from web/index.html and web/favicon.svg, do not edit"
  echo "#pragma once"
  echo "static const uint8_t PAGE_GZ[] PROGMEM = {"
  gzip -9nc web/index.html | xxd -i
  echo "};"
  echo "static const size_t PAGE_GZ_LEN = sizeof PAGE_GZ;"
  echo "static const uint8_t FAVICON_SVG[] PROGMEM = {"
  xxd -i < web/favicon.svg
  echo "};"
  echo "static const size_t FAVICON_SVG_LEN = sizeof FAVICON_SVG;"
} > super_remote/page_gz.h
arduino-cli compile --fqbn "$FQBN" --output-dir super_remote/build super_remote || exit 1
VER=$(grep -o '#define FW_VERSION "[^"]*"' super_remote/super_remote.ino | cut -d'"' -f2)
mkdir -p web/firmware
cp super_remote/build/super_remote.ino.bin web/firmware/revenant.bin
SIZE=$(stat -f%z web/firmware/revenant.bin)
printf '{"version":"%s","file":"revenant.bin","size":%s}\n' "$VER" "$SIZE" > web/firmware/version.json
echo "web/firmware now holds version $VER ($SIZE bytes)"
if [ "$1" = flash ]; then
  arduino-cli upload --fqbn "$FQBN" -p /dev/cu.usbmodem2101 --input-dir super_remote/build super_remote
fi
